/**
 * Corrects the `_headers` file that vinext generates into the client build.
 *
 * vinext writes a blanket rule:
 *
 *   /assets/*
 *     Cache-Control: public, max-age=31536000, immutable
 *
 * That is right for its own output (`index-CL2maLVU.css`, `SiteShell-Dr4fvJAx.js`,
 * hashed fonts) because those filenames change whenever the bytes change. But
 * everything in `public/assets` — our photography and video — lands in the same
 * `/assets/` prefix while keeping a stable filename. Marking those `immutable`
 * tells browsers never to revalidate for a year, so replacing an image in place
 * is invisible to anyone who has already visited, and a CDN purge cannot fix it
 * because the browser never asks again.
 *
 * The rules below are split by extension and deliberately do not overlap, so no
 * path can pick up two conflicting Cache-Control values.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const HEADERS_FILE = join("dist", "client", "_headers");

// Content-hashed by the bundler: the URL changes whenever the bytes do.
const IMMUTABLE = ["js", "css", "woff2", "woff"];
// Authored files copied verbatim from public/: stable URL, mutable bytes.
const REVALIDATE = ["jpg", "jpeg", "png", "svg", "webp", "avif", "mp4", "webm"];

const rule = (glob, value) => `${glob}\n  Cache-Control: ${value}\n`;

const contents = [
  "# Generated by vinext, then corrected by scripts/fix-asset-headers.mjs.\n",
  "# Content-hashed bundler output — safe to cache forever.\n",
  ...IMMUTABLE.map((ext) => rule(`/assets/*.${ext}`, "public, max-age=31536000, immutable")),
  "\n# Stable filenames from public/ — must revalidate so replacements go live.\n",
  ...REVALIDATE.map((ext) => rule(`/assets/*.${ext}`, "public, max-age=3600, must-revalidate")),
].join("");

let previous;
try {
  previous = readFileSync(HEADERS_FILE, "utf8");
} catch {
  console.error(`fix-asset-headers: ${HEADERS_FILE} not found — did the build run?`);
  process.exit(1);
}

if (!previous.includes("/assets/*")) {
  console.error("fix-asset-headers: unexpected _headers contents, refusing to overwrite:");
  console.error(previous);
  process.exit(1);
}

writeFileSync(HEADERS_FILE, contents);
console.log(`fix-asset-headers: rewrote ${HEADERS_FILE}`);
